#!/usr/bin/env node
// Precompiles the Config V3 JSON Schema into a self-contained validation module
// (src/manifest/config-v3-validator.generated.js). The Workers runtime forbids
// code generation from strings, so the schema cannot be compiled at runtime;
// Ajv's standalone output is bundled with its small runtime helpers so the
// module has no imports. Run `npm run generate:validator` after editing
// schemas/tapdeploy.config.v3.schema.json; a test fails when the file is stale.

import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const OUTPUT = fileURLToPath(new URL("../src/manifest/config-v3-validator.generated.js", import.meta.url));

export async function generateConfigValidator() {
  const schema = JSON.parse(readFileSync(new URL("../schemas/tapdeploy.config.v3.schema.json", import.meta.url), "utf8"));
  const ajv = new Ajv2020({ allErrors: true, strict: true, allowUnionTypes: true, validateFormats: true, code: { source: true, esm: true } });
  addFormats(ajv);
  const source = standaloneCode(ajv, ajv.compile(schema));
  const bundled = await build({
    stdin: { contents: source, resolveDir: root, loader: "js" },
    bundle: true,
    format: "esm",
    platform: "neutral",
    mainFields: ["main"],
    legalComments: "none",
    write: false,
  });
  return `// Generated by scripts/generate-config-validator.mjs from the config JSON Schema. Do not edit.\n${bundled.outputFiles[0].text}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, await generateConfigValidator());
  console.log(`[generate-config-validator] wrote ${OUTPUT}`);
}
